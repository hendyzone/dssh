import type { ThemePreset } from "./themes";

// Palette references and adaptation notes: docs/themes.md.
type Colors = [string, string, string, string, string, string];
function preset(
  id: string,
  name: string,
  description: string,
  category: "dark" | "light",
  bg: string,
  panel: string,
  fg: string,
  muted: string,
  border: string,
  colors: Colors,
): ThemePreset {
  const [red, green, yellow, blue, magenta, cyan] = colors;
  return {
    id,
    name,
    description,
    category,
    ui: {
      bg,
      panel,
      panelAlt: panel,
      fg,
      muted,
      border,
      accent: blue,
      danger: red,
    },
    term: {
      background: bg,
      foreground: fg,
      cursor: fg,
      cursorAccent: bg,
      selectionBackground: border,
      black: category === "dark" ? panel : "#343b45",
      red,
      green,
      yellow,
      blue,
      magenta,
      cyan,
      white: category === "dark" ? fg : "#d8dee9",
      brightBlack: muted,
      brightRed: red,
      brightGreen: green,
      brightYellow: yellow,
      brightBlue: blue,
      brightMagenta: magenta,
      brightCyan: cyan,
      brightWhite: category === "dark" ? "#f8f8f2" : "#f5f5f5",
    },
  };
}
