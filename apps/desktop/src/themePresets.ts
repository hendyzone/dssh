function mixed(
  id: string,
  name: string,
  description: string,
  ui: ThemePreset,
  terminal: ThemePreset,
  accent: string,
): ThemePreset {
  return {
    id,
    name,
    description,
    category: "mixed",
    ui: { ...ui.ui, accent },
    term: { ...terminal.term },
  };
}
